#!/usr/bin/env python3
"""Generate src/gui/fontdata.c: anti-aliased proportional UI font faces for printable ASCII (32..126).

Source: Poppins Regular and Poppins Medium (SIL Open Font License 1.1, (c) 2020 The Poppins Project Authors).
The OFL permits embedding and derived bitmap renderings; see docs/NOTICE-fonts.md.

Each face stores 8-bit coverage bitmaps (hinted FreeType rasterisation via Pillow), integer bearings and an
advance in 1/64 px, so text keeps natural rhythm without sub-pixel glyph rendering. Coverage is gamma-adjusted
(light text on dark backgrounds reads thin under plain sRGB blending). Output is deterministic for a given font file.

Usage: tools/gen-font-aa.py [FONT_DIR] > src/gui/fontdata.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

fdir = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/google-fonts"
FILES = {400: f"{fdir}/Poppins-Regular.ttf", 500: f"{fdir}/Poppins-Medium.ttf"}
# (weight, pixel size) - keep in step with the TY_* tokens in src/gui/theme.h
FACES = [(400, 11), (400, 12), (400, 13), (500, 12), (500, 13), (500, 14), (500, 20)]
GAMMA = 0.80
PAD, BASE = 12, 40            # canvas origin used while rasterising (glyph origin = baseline, left)
LUT = [min(255, int(round(255.0 * (i / 255.0) ** GAMMA))) for i in range(256)]

print("/* Generated by tools/gen-font-aa.py from Poppins Regular/Medium (SIL OFL 1.1, (c) 2020 The Poppins Project")
print(" * Authors; see docs/NOTICE-fonts.md). Do not edit. */")
print('#include "font.h"\n')
tables = []
for weight, px in FACES:
    font = ImageFont.truetype(FILES[weight], px)
    ascent, descent = font.getmetrics()
    capimg = Image.new("L", (64, 64), 0); ImageDraw.Draw(capimg).text((PAD, BASE), "H", font=font, fill=255, anchor="ls")
    cb = capimg.getbbox(); cap = BASE - cb[1]
    blob = bytearray(); glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        img = Image.new("L", (64, 64), 0); ImageDraw.Draw(img).text((PAD, BASE), ch, font=font, fill=255, anchor="ls")
        bb = img.getbbox()
        adv64 = int(round(font.getlength(ch) * 64))
        if bb is None:
            glyphs.append((len(blob), 0, 0, 0, 0, adv64)); continue
        crop = img.crop(bb); w, h = crop.size
        off = len(blob); blob.extend(LUT[v] for v in crop.tobytes())
        glyphs.append((off, w, h, bb[0] - PAD, BASE - bb[1], adv64))
    name = f"{'R' if weight == 400 else 'M'}{px}"
    tables.append((name, weight, px, ascent, descent, cap))
    print(f"static const uint8_t a_{name}[{len(blob)}] = {{")
    for i in range(0, len(blob), 24):
        print("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    print("};")
    print(f"static const FontGlyph g_{name}[95] = {{")
    for g in glyphs:
        print("    {%d,%d,%d,%d,%d,%d}," % g)
    print("};\n")
print("const Face aether_faces[] = {")
for name, weight, px, asc, desc, cap in tables:
    print(f"    {{ {px}, {asc}, {desc}, {cap}, {weight}, g_{name}, a_{name} }},")
print("};")
print(f"const int aether_nfaces = {len(tables)};")
